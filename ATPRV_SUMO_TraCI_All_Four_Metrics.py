def test_metric_engine():

    engine = ATPRVMetricEngine()

    veh_id = "veh0"

    # Mobility
    engine.compute_mobility_score(
        veh_id,
        0.0,
        (100.0, 100.0),
        15.0
    )

    M = engine.compute_mobility_score(
        veh_id,
        1.0,
        (114.5, 100.0),
        15.0
    )

    # Behavioral samples
    for index in range(20):

        engine.process_behavior_message(
            veh_id=veh_id,
            sim_time=index * 0.1,
            message_timestamp=index * 0.1,
            message_id=f"m{index}",
            speed=15.0,
            acceleration=0.5,
            authentication_valid=(
                index not in {7, 16}
            ),
            mobility_score=M,
        )

    # Communication samples
    for _ in range(50):

        engine.simulate_packet_transmission(
            veh_id,
            (150.0, 100.0),
            nearby_vehicle_count=20
        )

    # Authentication history
    for i in range(50):

        engine.record_authentication(
            veh_id,
            success=(i < 47)
        )

    B = engine.compute_behavior_score(
        veh_id
    )

    C = engine.compute_communication_score(
        veh_id
    )

    H = engine.compute_history_score(
        veh_id
    )

    trust = engine.update_trust(
        veh_id,
        B,
        M,
        C,
        H
    )

    risk = engine.compute_simple_risk(
        trust,
        B,
        M,
        C
    )

    decision = engine.decision(
        trust,
        risk
    )

    print("\nStandalone ATPRV metric test")
    print("----------------------------")
    print(f"B_i(t) = {B:.4f}")
    print(f"M_i(t) = {M:.4f}")
    print(f"C_i(t) = {C:.4f}")
    print(f"H_i(t) = {H:.4f}")
    print(f"T_i(t+1) = {trust:.4f}")
    print(f"R_i(t) = {risk:.4f}")
    print(f"Decision = {decision}")


