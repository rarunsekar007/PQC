# SUMO / TRACI MAIN LOOP
# ============================================================

def run_atprv_sumo():

    try:
        import traci
    except ImportError:
        raise SystemExit(
            "TraCI not found. Install/configure SUMO Python tools first."
        )

    engine = ATPRVMetricEngine()

    # Check trust normalization
    coefficient_sum = (
        (1.0 - ETA)
        + OMEGA_B
        + OMEGA_M
        + OMEGA_C
        + OMEGA_H
    )

    if abs(coefficient_sum - 1.0) > 1e-9:
        raise ValueError(
            "Trust coefficients must sum to 1."
        )

    traci.start(
        [
            "sumo",
            "-c",
            SUMO_CONFIG
        ]
    )

    last_metric_time = 0.0

    # Store latest communication probability
    latest_p_success = defaultdict(lambda: 1.0)

    try:

        while (
            traci.simulation.getMinExpectedNumber()
            > 0
        ):

            traci.simulationStep()

            sim_time = (
                traci.simulation.getTime()
            )

            vehicle_ids = list(
                traci.vehicle.getIDList()
            )

            # ------------------------------------------------
            # Number of vehicles near RSU
            # ------------------------------------------------
            vehicles_near_rsu = 0

            for vid in vehicle_ids:

                pos = (
                    traci.vehicle.getPosition(vid)
                )

                if (
                    engine.distance(
                        pos,
                        RSU_POSITION
                    )
                    <= COMMUNICATION_RANGE
                ):
                    vehicles_near_rsu += 1

            # ------------------------------------------------
            # Process each vehicle
            # ------------------------------------------------
            for veh_id in vehicle_ids:

                position = (
                    traci.vehicle.getPosition(
                        veh_id
                    )
                )

                speed = (
                    traci.vehicle.getSpeed(
                        veh_id
                    )
                )

                acceleration = (
                    traci.vehicle.getAcceleration(
                        veh_id
                    )
                )

                # ============================================
                # M_i(t): directly from TraCI
                # ============================================
                M = engine.compute_mobility_score(
                    veh_id,
                    sim_time,
                    position,
                    speed
                )

                # ============================================
                # Simulated beacon / authentication message
                # ============================================
                message_timestamp = sim_time

                message_id = (
                    f"{veh_id}_{sim_time:.3f}"
                )

                # Actual ATPRV verification should replace
                # this demonstration function.
                auth_success = (
                    atprv_authentication_result(
                        veh_id,
                        sim_time
                    )
                )

                engine.record_authentication(
                    veh_id,
                    auth_success
                )

                # ============================================
                # B_i(t): protocol + mobility observations
                # ============================================
                engine.process_behavior_message(
                    veh_id=veh_id,
                    sim_time=sim_time,
                    message_timestamp=message_timestamp,
                    message_id=message_id,
                    speed=speed,
                    acceleration=acceleration,
                    authentication_valid=auth_success,
                    mobility_score=M,
                )

                # ============================================
                # C_i(t): Python communication abstraction
                # ============================================
                received, p_success = (
                    engine.simulate_packet_transmission(
                        veh_id,
                        position,
                        vehicles_near_rsu
                    )
                )

                latest_p_success[
                    veh_id
                ] = p_success

                # Optional:
                # if packet was not received, the RSU would
                # not actually process the message.
                #
                # For a stricter event-order implementation,
                # perform reception simulation BEFORE behavior
                # and authentication processing.

            # ------------------------------------------------
            # Calculate metrics once per observation window
            # ------------------------------------------------
            if (
                sim_time - last_metric_time
                >= OBSERVATION_WINDOW
            ):

                print(
                    "\nTime:",
                    round(sim_time, 2)
                )

                for veh_id in vehicle_ids:

                    B = (
                        engine.compute_behavior_score(
                            veh_id
                        )
                    )

                    M = (
                        engine.vehicle[
                            veh_id
                        ].latest_mobility_score
                    )

                    C = (
                        engine.compute_communication_score(
                            veh_id
                        )
                    )

                    H = (
                        engine.compute_history_score(
                            veh_id
                        )
                    )

                    trust = engine.update_trust(
                        veh_id,
                        B,
                        M,
                        C,
                        H
                    )

                    risk = (
                        engine.compute_simple_risk(
                            trust,
                            B,
                            M,
                            C
                        )
                    )

                    decision = (
                        engine.decision(
                            trust,
                            risk
                        )
                    )

                    print(
                        veh_id,
                        f"B={B:.3f}",
                        f"M={M:.3f}",
                        f"C={C:.3f}",
                        f"H={H:.3f}",
                        f"T={trust:.3f}",
                        f"R={risk:.3f}",
                        decision
                    )

                    write_csv(
                        sim_time,
                        veh_id,
                        B,
                        M,
                        C,
                        H,
                        trust,
                        risk,
                        decision,
                        latest_p_success[
                            veh_id
                        ]
                    )

                    engine.reset_observation_window(
                        veh_id
                    )

                last_metric_time = sim_time

    finally:
        traci.close()


